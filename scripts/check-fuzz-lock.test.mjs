// Tests du contrôle d'alignement des verrous (scripts/check-fuzz-lock.mjs),
// lancés par ./scripts/check.sh avec `node --test`.
import { test } from "node:test";
import assert from "node:assert/strict";
import {
  lockPackages,
  lockProblems,
  misalignedPackages,
} from "./check-fuzz-lock.mjs";

const REGISTRY = "registry+https://github.com/rust-lang/crates.io-index";

function pkg(name, version, checksum) {
  let block = `[[package]]\nname = "${name}"\nversion = "${version}"\n`;
  if (checksum) block += `source = "${REGISTRY}"\nchecksum = "${checksum}"\n`;
  return block + `dependencies = [\n "x",\n]\n`;
}

function lock(...packages) {
  return `# This file is automatically @generated by Cargo.\nversion = 4\n\n${packages.join("\n")}`;
}

test("lit nom, version, source et empreinte de chaque paquet", () => {
  const text = lock(
    pkg("ammonia", "4.2.5", "aa"),
    pkg("norelly-render", "0.1.0"),
  );
  assert.deepEqual(lockPackages(text), [
    { name: "ammonia", version: "4.2.5", source: REGISTRY, checksum: "aa" },
    {
      name: "norelly-render",
      version: "0.1.0",
      source: undefined,
      checksum: undefined,
    },
  ]);
});

test("verrous alignés : aucun écart", () => {
  const root = lock(pkg("ammonia", "4.2.5", "aa"), pkg("cc", "1.10.0", "cc1"));
  const fuzz = lock(pkg("ammonia", "4.2.5", "aa"), pkg("cc", "1.10.0", "cc1"));
  assert.deepEqual(misalignedPackages(root, fuzz), []);
});

test("une version différente de la racine est signalée", () => {
  const root = lock(pkg("ammonia", "4.2.5", "aa"));
  const fuzz = lock(pkg("ammonia", "4.2.4", "bb"));
  assert.deepEqual(misalignedPackages(root, fuzz), [
    "ammonia 4.2.4 (racine : 4.2.5)",
  ]);
});

test("une empreinte différente pour la même version est signalée", () => {
  const root = lock(pkg("flate2", "1.1.10", "aa"));
  const fuzz = lock(pkg("flate2", "1.1.10", "zz"));
  assert.deepEqual(misalignedPackages(root, fuzz), [
    "flate2 1.1.10 (racine : 1.1.10)",
  ]);
});

test("une version présente parmi plusieurs versions de la racine est admise", () => {
  const root = lock(pkg("syn", "1.0.109", "s1"), pkg("syn", "2.0.100", "s2"));
  const fuzz = lock(pkg("syn", "2.0.100", "s2"));
  assert.deepEqual(misalignedPackages(root, fuzz), []);
});

test("les paquets propres au fuzzing et ceux du dépôt sont ignorés", () => {
  const root = lock(pkg("norelly-render", "0.1.0"));
  const fuzz = lock(
    pkg("libfuzzer-sys", "0.4.13", "lf"),
    pkg("norelly-render", "0.1.0"),
  );
  assert.deepEqual(misalignedPackages(root, fuzz), []);
});

test("des verrous aux fins de ligne CRLF sont lus de même", () => {
  const crlf = (text) => text.replaceAll("\n", "\r\n");
  const root = crlf(lock(pkg("ammonia", "4.2.5", "aa")));
  assert.equal(lockPackages(root).length, 1);
  assert.deepEqual(
    misalignedPackages(root, crlf(lock(pkg("ammonia", "4.2.4", "bb")))),
    ["ammonia 4.2.4 (racine : 4.2.5)"],
  );
});

test("verrous lisibles et alignés : aucun problème", () => {
  const root = lock(pkg("ammonia", "4.2.5", "aa"));
  const fuzz = lock(
    pkg("ammonia", "4.2.5", "aa"),
    pkg("arbitrary", "1.5.0", "ar"),
  );
  assert.deepEqual(lockProblems(root, fuzz), []);
});

test("un verrou sans paquet reconnu est un problème, pas un alignement", () => {
  const fuzz = lock(pkg("ammonia", "4.2.5", "aa"));
  assert.deepEqual(lockProblems("", fuzz), ["Cargo.lock : aucun paquet lu"]);
  assert.deepEqual(
    lockProblems(fuzz.replaceAll("[[package]]", "[[ package ]]"), fuzz),
    ["Cargo.lock : aucun paquet lu"],
  );
});

test("un bloc sans nom ou sans version est un problème", () => {
  const root = lock(pkg("ammonia", "4.2.5", "aa"));
  const fuzz = lock(
    pkg("ammonia", "4.2.5", "aa"),
    '[[package]]\nname = "cc"\n',
  );
  assert.deepEqual(lockProblems(root, fuzz), [
    "fuzz/Cargo.lock : paquet sans nom ou sans version",
  ]);
});

test("aucun paquet commun aux deux verrous est un problème", () => {
  const root = lock(pkg("ammonia", "4.2.5", "aa"));
  const fuzz = lock(pkg("libfuzzer-sys", "0.4.13", "lf"));
  assert.deepEqual(lockProblems(root, fuzz), [
    "aucun paquet commun à Cargo.lock et fuzz/Cargo.lock",
  ]);
});

test("un écart de version figure parmi les problèmes", () => {
  const root = lock(pkg("ammonia", "4.2.5", "aa"), pkg("cc", "1.10.0", "c"));
  const fuzz = lock(pkg("ammonia", "4.2.4", "bb"), pkg("cc", "1.10.0", "c"));
  assert.deepEqual(lockProblems(root, fuzz), [
    "fuzz/Cargo.lock : ammonia 4.2.4 (racine : 4.2.5)",
  ]);
});

test("lancé par un chemin qui traverse un lien symbolique, le contrôle s'exécute", async () => {
  const { execFileSync } = await import("node:child_process");
  const { mkdtempSync, symlinkSync, rmSync } = await import("node:fs");
  const os = await import("node:os");
  const path = await import("node:path");
  const { fileURLToPath } = await import("node:url");
  const scripts = path.dirname(fileURLToPath(import.meta.url));
  const dir = mkdtempSync(path.join(os.tmpdir(), "norelly-lien-"));
  try {
    const link = path.join(dir, "scripts");
    try {
      symlinkSync(scripts, link, "dir");
    } catch {
      return; // pas de lien symbolique possible (Windows sans droits)
    }
    const out = execFileSync(process.execPath, [path.join(link, "check-fuzz-lock.mjs")], {
      encoding: "utf8",
    });
    assert.match(out, /aligné sur Cargo.lock/);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});
